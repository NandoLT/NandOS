import { cleanup, fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { INITIAL_WIKI_ARTICLES, WIKI_DOCUMENTED_APP_IDS } from '@nandoos/contracts'
import { renderWithProviders } from '../../../test/render'
import { appRegistry } from '../../applications/domain/app-registry'
import { createPreviewWikiRepository } from '../infrastructure/preview-repository'
import { MarkdownPreview } from './MarkdownPreview'
import { WikiPanel } from './WikiPanel'

afterEach(() => { cleanup(); vi.restoreAllMocks() })

describe('Wiki editor', () => {
  it('invalidates synchronization on publication/withdrawal but not on private draft saves', async () => {
    const repository = createPreviewWikiRepository()
    const original = await repository.create({ title: 'Guía', category: 'Ayuda', markdown: '# Texto' })
    await repository.publish(original.id, original.revision)
    const publishedKey = async () => JSON.stringify((await repository.list()).map((a) => [a.id, a.publishedRevision, a.published]))
    let indexed = await publishedKey()
    const status = vi.fn(async () => ({ state: indexed === await publishedKey() ? 'updated' as const : 'outdated' as const,
      publishedArticles: 1, indexedArticles: 1, indexedChunks: 1 }))
    repository.synchronization = { status, async synchronize() { indexed = await publishedKey(); return status() } }
    renderWithProviders(<WikiPanel repository={repository} />)
    const user = userEvent.setup()
    await screen.findByText('Actualizado')
    await user.click(await screen.findByRole('button', { name: /Guía Ayuda Publicado/ }))
    fireEvent.change(screen.getByLabelText('Contenido Markdown'), { target: { value: '# Edición privada' } })
    await user.click(screen.getByRole('button', { name: 'Guardar borrador' }))
    await waitFor(async () => expect((await repository.list())[0]!.draft.markdown).toBe('# Edición privada'))
    expect(screen.getByText('Actualizado')).toBeInTheDocument()
    expect(status).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Publicar artículo' }))
    await screen.findByText('Desactualizado')
    await waitFor(() => expect(screen.getByRole('button', { name: 'Sincronizar wiki' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: 'Sincronizar wiki' }))
    await screen.findByText('Actualizado')
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    await user.click(screen.getByRole('button', { name: 'Retirar publicación' }))
    await screen.findByText('Desactualizado')
  })
  it('offers all existing categories in a real selector when creating an article', async () => {
    const repository = createPreviewWikiRepository()
    await repository.seed()
    renderWithProviders(<WikiPanel repository={repository} />)
    const user = userEvent.setup()
    await screen.findByRole('button', { name: /Bienvenido a NandOS/ })
    const selector = screen.getByRole('combobox', { name: 'Categoría del artículo' })
    expect(selector.tagName).toBe('SELECT')
    for (const name of ['General', 'Menú Start', 'Asistente', 'Aplicaciones futuras'])
      expect(within(selector).getByRole('option', { name })).toBeInTheDocument()
    await user.selectOptions(selector, 'Asistente')
    await user.type(screen.getByLabelText('Título'), 'Nuevo artículo de ayuda')
    fireEvent.change(screen.getByLabelText('Contenido Markdown'), { target: { value: '# Ayuda' } })
    await user.click(screen.getByRole('button', { name: 'Guardar borrador' }))
    await waitFor(async () => expect((await repository.list()).find((a) => a.draft.title === 'Nuevo artículo de ayuda')?.draft.category).toBe('Asistente'))
  })
  it('adds categories, keeps them after saving an article and reuses existing names without duplicates', async () => {
    const repository = createPreviewWikiRepository()
    renderWithProviders(<WikiPanel repository={repository} />)
    const user = userEvent.setup()
    await waitFor(() => expect(screen.getByRole('button', { name: '+ Nuevo artículo' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: 'Nueva categoría' }))
    await user.type(screen.getByLabelText('Nombre de la nueva categoría'), '  Guías avanzadas  ')
    await user.click(screen.getByRole('button', { name: 'Añadir categoría' }))
    expect(screen.getByLabelText('Categoría del artículo')).toHaveValue('Guías avanzadas')
    await user.type(screen.getByLabelText('Título'), 'Guía nueva')
    fireEvent.change(screen.getByLabelText('Contenido Markdown'), { target: { value: '# Guía' } })
    await user.click(screen.getByRole('button', { name: 'Guardar borrador' }))
    await waitFor(async () => expect((await repository.list())[0]?.draft.category).toBe('Guías avanzadas'))
    await user.click(screen.getByRole('button', { name: '+ Nuevo artículo' }))
    const selector = screen.getByLabelText('Categoría del artículo')
    await user.selectOptions(selector, 'Guías avanzadas')
    expect(selector).toHaveValue('Guías avanzadas')
    await user.click(screen.getByRole('button', { name: 'Nueva categoría' }))
    await user.type(screen.getByLabelText('Nombre de la nueva categoría'), ' GUÍAS AVANZADAS ')
    await user.click(screen.getByRole('button', { name: 'Añadir categoría' }))
    expect(selector).toHaveValue('Guías avanzadas')
    expect(within(selector).getAllByRole('option', { name: /guías avanzadas/i })).toHaveLength(1)
  })
  it('cancels category creation without changing the selection and rejects blank names', async () => {
    renderWithProviders(<WikiPanel repository={createPreviewWikiRepository()} />)
    const user = userEvent.setup()
    await waitFor(() => expect(screen.getByRole('button', { name: '+ Nuevo artículo' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: 'Nueva categoría' }))
    const name = screen.getByLabelText('Nombre de la nueva categoría')
    expect(name).toHaveFocus()
    await user.type(name, '   ')
    expect(screen.getByRole('button', { name: 'Añadir categoría' })).toBeDisabled()
    await user.keyboard('{Escape}')
    expect(screen.queryByLabelText('Nombre de la nueva categoría')).not.toBeInTheDocument()
    expect(screen.getByLabelText('Categoría del artículo')).toHaveValue('General')
    expect(screen.getByLabelText('Categoría del artículo')).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Nueva categoría' }))
    await user.type(screen.getByLabelText('Nombre de la nueva categoría'), 'Descartada')
    await user.tab()
    await user.tab()
    expect(screen.getByRole('button', { name: 'Cancelar' })).toHaveFocus()
    await user.keyboard('{Enter}')
    expect(screen.queryByLabelText('Nombre de la nueva categoría')).not.toBeInTheDocument()
    expect(screen.getByLabelText('Categoría del artículo')).toHaveValue('General')
  })
  it('documents every registered application and all Start sections', () => {
    expect([...WIKI_DOCUMENTED_APP_IDS].sort()).toEqual(appRegistry.map((app) => app.id).sort())
    for (const name of ['Start: menú principal', 'Start > Programas', 'Start > Documentos', 'Start > Configuración y Apariencia', 'Start > Buscar, Ayuda y Ejecutar', 'Log off Invitado y Apagar'])
      expect(INITIAL_WIKI_ARTICLES.some((article) => article.draft.title === name)).toBe(true)
    expect(new Set(INITIAL_WIKI_ARTICLES.map((article) => article.id)).size).toBe(INITIAL_WIKI_ARTICLES.length)
  })
  it('creates, saves, publishes and edits independently from the published snapshot', async () => {
    const repository = createPreviewWikiRepository()
    renderWithProviders(<WikiPanel repository={repository} />)
    const user = userEvent.setup()
    await waitFor(() => expect(screen.getByRole('button', { name: '+ Nuevo artículo' })).toBeEnabled())
    await user.type(screen.getByLabelText('Título'), 'Mi artículo')
    fireEvent.change(screen.getByLabelText('Contenido Markdown'), { target: { value: '# Hola wiki\n\n**Contenido inicial**' } })
    expect(screen.getByRole('heading', { name: 'Hola wiki' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Publicar artículo' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Guardar borrador' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Publicar artículo' })).toBeEnabled())
    expect((await repository.list())[0]!.published).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Publicar artículo' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Retirar publicación' })).toBeInTheDocument())
    expect(screen.queryByRole('button', { name: 'Previsualizar borrador' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Ver versión publicada' })).not.toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Contenido Markdown'), { target: { value: '# Borrador privado' } })
    await user.click(screen.getByRole('button', { name: 'Guardar borrador' }))
    await waitFor(async () => expect((await repository.list())[0]!.draft.markdown).toBe('# Borrador privado'))
    expect(within(screen.getByLabelText('Vista previa del artículo')).getByRole('heading', { name: 'Borrador privado' })).toBeInTheDocument()
    expect((await repository.list())[0]!.published?.markdown).toContain('Contenido inicial')
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    await user.click(screen.getByRole('button', { name: 'Retirar publicación' }))
    await waitFor(async () => expect((await repository.list())[0]!.published).toBeNull())
    expect((await repository.list())[0]!.draft.markdown).toBe('# Borrador privado')
    vi.restoreAllMocks()
  })
  it('imports drafts idempotently and filters categories and text', async () => {
    const repository = createPreviewWikiRepository()
    renderWithProviders(<WikiPanel repository={repository} />)
    const user = userEvent.setup()
    await waitFor(() => expect(screen.getByRole('button', { name: 'Cargar documentación inicial' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: 'Cargar documentación inicial' }))
    await screen.findByRole('button', { name: /Bienvenido a NandOS/ })
    expect((await repository.list()).every((article) => article.published === null)).toBe(true)
    await user.selectOptions(screen.getByLabelText('Categoría'), 'Aplicaciones futuras')
    await user.type(screen.getByLabelText('Buscar artículo'), 'Buscaminas')
    const list = screen.getByLabelText('Lista de artículos')
    expect(within(list).getAllByRole('button')).toHaveLength(1)
    expect(within(list).getByRole('button', { name: /Buscaminas/ })).toBeInTheDocument()
    expect(await repository.seed()).toBe(0)
  })
  it('warns before discarding unsaved edits and keeps text after save conflicts', async () => {
    const repository = createPreviewWikiRepository()
    const article = await repository.create({ title: 'Primero', category: 'Ayuda', markdown: '# Texto' })
    renderWithProviders(<WikiPanel repository={repository} />)
    const user = userEvent.setup()
    await user.click(await screen.findByRole('button', { name: /Primero Ayuda Borrador/ }))
    fireEvent.change(screen.getByLabelText('Contenido Markdown'), { target: { value: 'Mi edición local' } })
    const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false)
    await user.click(screen.getByRole('button', { name: '+ Nuevo artículo' }))
    expect(screen.getByLabelText('Contenido Markdown')).toHaveValue('Mi edición local')
    await repository.save(article.id, { ...article.draft, markdown: 'Otra edición' }, article.revision)
    await user.click(screen.getByRole('button', { name: 'Guardar borrador' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Otra edición')
    expect(screen.getByLabelText('Contenido Markdown')).toHaveValue('Mi edición local')
    expect(confirm).toHaveBeenCalled()
    vi.restoreAllMocks()
  })
})

it('renders Markdown without HTML execution, unsafe links or external image requests', () => {
  const { container } = renderWithProviders(<MarkdownPreview markdown={'# Seguro\n\n<script>alert(1)</script>\n\n[Malicioso](javascript:alert)\n\n![externa](https://tracking.test/pixel.png)\n\n[Web](https://example.com)'} />)
  expect(container.querySelector('script')).toBeNull()
  expect(container.querySelector('img')).toBeNull()
  expect(screen.getByText('Malicioso')).not.toHaveAttribute('href', 'javascript:alert')
  expect(screen.getByRole('link', { name: 'Web' })).toHaveAttribute('rel', 'noopener noreferrer')
})
